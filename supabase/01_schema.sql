-- ---------------------------------------------------------------------------
-- Tabelas
-- ---------------------------------------------------------------------------

create table public.categorias (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users(id) on delete restrict,
  nome        varchar(50) not null check (length(btrim(nome)) > 0),
  cor         char(7) not null default '#64748b' check (cor ~ '^#[0-9a-fA-F]{6}$'),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- alvo da FK composta de lancamentos: garante que a categoria é do mesmo usuário
  unique (id, user_id)
);

create unique index categorias_nome_unico on public.categorias (user_id, lower(btrim(nome)));

create table public.lancamentos (
  id            bigint generated by default as identity primary key,
  -- "restrict": apagar o usuário do Auth nunca apaga os lançamentos junto
  user_id       uuid not null default auth.uid() references auth.users(id) on delete restrict,
  data          date not null default (now() at time zone 'America/Sao_Paulo')::date,
  tipo          text not null check (tipo in ('receita', 'despesa')),
  valor         numeric(14,2) not null check (valor >= 0),
  descricao     varchar(255) not null, -- há 1 lançamento antigo com descrição vazia
  categoria_id  bigint,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  -- excluir uma categoria só tira a categoria dos lançamentos (não apaga nada)
  foreign key (categoria_id, user_id) references public.categorias (id, user_id)
    on delete set null (categoria_id)
);

create index lancamentos_user_data_idx on public.lancamentos (user_id, data desc, id desc);
create index lancamentos_user_categoria_idx on public.lancamentos (user_id, categoria_id);

-- ---------------------------------------------------------------------------
-- Integridade: dono e data de criação nunca mudam; updated_at automático
-- ---------------------------------------------------------------------------

create or replace function public.proteger_colunas()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  new.user_id := old.user_id;
  new.created_at := old.created_at;
  return new;
end $$;

create trigger proteger_colunas before update on public.categorias
  for each row execute function public.proteger_colunas();
create trigger proteger_colunas before update on public.lancamentos
  for each row execute function public.proteger_colunas();

-- ---------------------------------------------------------------------------
-- Segurança: cada usuário só enxerga e altera os próprios dados
-- ---------------------------------------------------------------------------

alter table public.categorias enable row level security;
alter table public.lancamentos enable row level security;

-- a Supabase concede tudo (inclusive TRUNCATE) por padrão; deixamos só o necessário
revoke all on public.categorias, public.lancamentos from anon, authenticated, public;
grant select, insert, update, delete on public.categorias, public.lancamentos to authenticated;

create policy "ver as suas" on public.categorias for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "criar as suas" on public.categorias for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "editar as suas" on public.categorias for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "excluir as suas" on public.categorias for delete to authenticated
  using ((select auth.uid()) = user_id);

create policy "ver os seus" on public.lancamentos for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "criar os seus" on public.lancamentos for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "editar os seus" on public.lancamentos for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "excluir os seus" on public.lancamentos for delete to authenticated
  using ((select auth.uid()) = user_id);

-- ---------------------------------------------------------------------------
-- Resumos calculados no banco (security invoker: o RLS acima continua valendo)
-- ---------------------------------------------------------------------------

-- Filtro único usado pela lista (com paginação via PostgREST) e pelos totais,
-- para que os dois nunca divirjam.
-- p_categoria: null = todas; 0 = só "sem categoria"; >0 = a categoria
-- p_busca é texto literal: % e _ digitados não viram curinga
create or replace function public.lancamentos_filtrados(
  p_inicio date default null, p_fim date default null,
  p_tipo text default null, p_categoria bigint default null,
  p_busca text default null, p_valor numeric default null
)
returns setof public.lancamentos
language sql stable security invoker set search_path = '' as $$
  select l.* from public.lancamentos l
  where (p_inicio is null or l.data >= p_inicio)
    and (p_fim is null or l.data <= p_fim)
    and (p_tipo is null or l.tipo = p_tipo)
    and (p_categoria is null
         or (p_categoria = 0 and l.categoria_id is null)
         or l.categoria_id = p_categoria)
    and (coalesce(btrim(p_busca), '') = ''
         or l.descricao ilike '%' || replace(replace(replace(btrim(p_busca), '\', '\\'), '%', '\%'), '_', '\_') || '%')
    and (p_valor is null or l.valor = p_valor);
$$;

create or replace function public.resumo_periodo(
  p_inicio date default null, p_fim date default null,
  p_tipo text default null, p_categoria bigint default null,
  p_busca text default null, p_valor numeric default null
)
returns table (receitas numeric, despesas numeric, saldo numeric, quantidade bigint)
language sql stable security invoker set search_path = '' as $$
  with f as (
    select tipo, valor from public.lancamentos_filtrados(p_inicio, p_fim, p_tipo, p_categoria, p_busca, p_valor)
  )
  select coalesce(sum(valor) filter (where tipo = 'receita'), 0),
         coalesce(sum(valor) filter (where tipo = 'despesa'), 0),
         coalesce(sum(valor) filter (where tipo = 'receita'), 0)
           - coalesce(sum(valor) filter (where tipo = 'despesa'), 0),
         count(*)
  from f;
$$;

-- totais por mês, incluindo meses sem lançamentos
create or replace function public.resumo_mensal(p_inicio date, p_fim date)
returns table (mes date, receitas numeric, despesas numeric)
language sql stable security invoker set search_path = '' as $$
  select m::date,
         coalesce(sum(l.valor) filter (where l.tipo = 'receita'), 0),
         coalesce(sum(l.valor) filter (where l.tipo = 'despesa'), 0)
  from generate_series(date_trunc('month', p_inicio::timestamp), date_trunc('month', p_fim::timestamp),
                       interval '1 month') m
  left join public.lancamentos l
    on l.data >= m::date and l.data < (m + interval '1 month')::date
  group by m
  order by m;
$$;

create or replace function public.resumo_por_categoria(p_inicio date, p_fim date, p_tipo text default 'despesa')
returns table (categoria_id bigint, nome text, cor text, total numeric, quantidade bigint)
language sql stable security invoker set search_path = '' as $$
  select l.categoria_id, coalesce(c.nome, 'Sem categoria'), coalesce(c.cor, '#94a3b8'),
         sum(l.valor), count(*)
  from public.lancamentos l
  left join public.categorias c on c.id = l.categoria_id
  where l.data between p_inicio and p_fim and l.tipo = p_tipo
  group by l.categoria_id, c.nome, c.cor
  order by sum(l.valor) desc;
$$;

revoke execute on function public.lancamentos_filtrados, public.resumo_periodo, public.resumo_mensal,
  public.resumo_por_categoria from public, anon;
revoke execute on function public.proteger_colunas from public, anon, authenticated;
grant execute on function public.lancamentos_filtrados, public.resumo_periodo, public.resumo_mensal,
  public.resumo_por_categoria to authenticated;
